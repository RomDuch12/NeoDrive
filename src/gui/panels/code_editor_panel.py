    def ouvrir_le_manuel(self) -> str:
        """F1: le manuel SimPL, à la page de la commande sous le
        curseur (rend le message à afficher)."""
        from PySide6.QtCore import QUrl
        from PySide6.QtGui import QDesktopServices
        from src.core.simpl_commandes import COMMANDES, chemin_manuel
        curseur = self.textCursor()
        curseur.select(curseur.SelectionType.WordUnderCursor)
        nom = curseur.selectedText().strip()
        manuel = chemin_manuel()
        info = COMMANDES.get(nom)
        if not manuel:
            return ("Manuel SimPL absent (DATRON_SimPL_Programmierhandbuch"
                    "_3.1.1_EN.pdf à côté de l'exe)")
        url = QUrl.fromLocalFile(manuel)
        if info:
            url.setFragment(f"page={info[3]}")
        QDesktopServices.openUrl(url)
        return (f"{nom}: manuel § {info[2]}, p. {info[3]}" if info
                else "Manuel SimPL ouvert")

    def keyPressEvent(self, event):
        mods = event.modifiers()
        key = event.key()
        if key == Qt.Key.Key_F and \
                mods & Qt.KeyboardModifier.ControlModifier:
            self.show_find_bar()
            return
        if key == Qt.Key.Key_F1:
            texte = self.ouvrir_le_manuel()
            from PySide6.QtWidgets import QToolTip
            QToolTip.showText(self.mapToGlobal(
                self.cursorRect().bottomRight()), texte, self)
            return
        if key == Qt.Key.Key_F3:
            bar = self.find_bar()
            if bar.edit.text():
                bar.find_next(
                    backward=bool(mods
                                  & Qt.KeyboardModifier.ShiftModifier))
                return
        if key == Qt.Key.Key_Escape and self._find_bar is not None \
                and self._find_bar.isVisible():
            self._find_bar.close_bar()
            return
        super().keyPressEvent(event)

    def line_number_area_paint_event(self, event):
        # Guard: don't paint if widget has no valid size
        if (self._line_number_area.width() <= 0 or
                self._line_number_area.height() <= 0):
            return

        painter = QPainter(self._line_number_area)
        if not painter.isActive():
            return

        painter.fillRect(event.rect(), QColor("#181825"))

        block = self.firstVisibleBlock()
        block_number = block.blockNumber()
        top = round(self.blockBoundingGeometry(block)
                    .translated(self.contentOffset()).top())
        bottom = top + round(self.blockBoundingRect(block).height())

        # Largeur de la zone numéros (sans fold markers)
        num_width = self._line_number_area.width() - self._FOLD_MARKER_SIZE - 6
        fold_x = num_width + 2  # position X des triangles
        fh = self.fontMetrics().height()

        fold_starts = self._fold_starts

        while block.isValid() and top <= event.rect().bottom():
            if block.isVisible() and bottom >= event.rect().top():
                number = str(block_number + 1)
                painter.setPen(QColor("#585b70"))
                painter.drawText(
                    0, top, num_width - 4, fh,
                    Qt.AlignmentFlag.AlignRight, number)

                # Fold marker
                if block_number in fold_starts:
                    is_folded = block_number in self._folded_blocks
                    self._draw_fold_marker(
                        painter, fold_x, top, fh, is_folded)

            block = block.next()
            top = bottom
            bottom = top + round(self.blockBoundingRect(block).height())
            block_number += 1

        painter.end()

    def _draw_fold_marker(self, painter: QPainter,
                          x: int, y: int, height: int,
                          is_folded: bool):
        """Dessine un triangle ▶ (plié) ou ▼ (déplié)."""
        sz = self._FOLD_MARKER_SIZE
        cy = y + height // 2
        cx = x + sz // 2

        painter.setPen(Qt.PenStyle.NoPen)
        painter.setBrush(QColor("#89b4fa"))

        if is_folded:
            # Triangle ▶ (pointant droite)
            tri = QPolygonF([
                QPointF(cx - 2, cy - sz // 2),
                QPointF(cx + sz // 2, cy),
                QPointF(cx - 2, cy + sz // 2),
            ])
        else:
            # Triangle ▼ (pointant bas)
            tri = QPolygonF([
                QPointF(cx - sz // 2, cy - 2),
                QPointF(cx + sz // 2, cy - 2),
                QPointF(cx, cy + sz // 2),
            ])

        painter.drawPolygon(tri)

    def line_number_area_mouse_press(self, event):
        """Gère le clic dans la zone de fold."""
        if event.button() != Qt.MouseButton.LeftButton:
            return

        # Déterminer quelle ligne a été cliquée
        block = self.firstVisibleBlock()
        top = round(self.blockBoundingGeometry(block)
                    .translated(self.contentOffset()).top())
        bottom = top + round(self.blockBoundingRect(block).height())

        click_y = event.position().toPoint().y()
        num_width = self._line_number_area.width() - self._FOLD_MARKER_SIZE - 6
        click_x = event.position().toPoint().x()

        # Vérifier si le clic est dans la zone fold
        if click_x < num_width:
            return  # clic dans les numéros de ligne, ignorer

        while block.isValid() and top <= click_y:
            if block.isVisible() and top <= click_y < bottom:
                line_num = block.blockNumber()
                # Vérifier si c'est une ligne de début de fold
                if line_num in self._fold_starts:
                    self.toggle_fold(line_num)
                return

            block = block.next()
            top = bottom
            bottom = top + round(self.blockBoundingRect(block).height())


