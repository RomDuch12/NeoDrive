    def match_positions(self):
        """Positions des occurrences de la recherche courante."""
        if not self._search_text:
            return []
        text = self.toPlainText()
        needle = self._search_text
        if not self._search_case:
            text, needle = text.lower(), needle.lower()
        out = []
        pos = text.find(needle)
        while pos >= 0 and len(out) < 10000:
            out.append(pos)
            pos = text.find(needle, pos + len(needle))
        return out

    def highlight_matches(self, text: str, case_sensitive: bool):
        """Surligne toutes les occurrences (vide = efface)."""
        self._search_text = text or ""
        self._search_case = bool(case_sensitive)
        self._search_selections = []
        if self._search_text:
            fmt_color = QColor(COLORS['yellow'])
            fmt_color.setAlpha(90)
            doc = self.document()
            for pos in self.match_positions():
                sel = QTextEdit.ExtraSelection()
                sel.format.setBackground(fmt_color)
                cursor = QTextCursor(doc)
                cursor.setPosition(pos)
                cursor.setPosition(pos + len(self._search_text),
                                   QTextCursor.MoveMode.KeepAnchor)
                sel.cursor = cursor
                self._search_selections.append(sel)
        self._highlight_current_line()

    def ensure_line_visible(self, line: int):
        """Déplie ce qu'il faut pour qu'une ligne soit affichée.

        Un résultat trouvé dans un bloc replié resterait invisible: le
        curseur y serait sans que rien ne bouge à l'écran."""
        changed = False
        for start, end, _name in self._fold_regions:
            if start < line <= end and start in self._folded_blocks:
                self._unfold_block(start, refresh=False)
                changed = True
        if changed:
            self._refresh_folding()
            self.ensureCursorVisible()

