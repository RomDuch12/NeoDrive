# Compilées une fois (utilisées ligne par ligne sur tout le document)
_RE_PROGRAM = re.compile(r'^program\s+(\w+)', re.IGNORECASE)
_RE_ENDPROGRAM = re.compile(r'^endprogram\b', re.IGNORECASE)
# Séquences Datron ($$$ SEQUENCE_N) et leurs passes en Z: un bloc $$$
# fait couramment des milliers de lignes, illisible sans pliage.
_RE_SEQ = re.compile(r'^\$\$\$\s*(\S+)')
_RE_SEQ_CUT = re.compile(r'^(Line|Arc\s+C?CW)\b')
_RE_SEQ_MOVE = re.compile(r'^(Line|Arc\s+C?CW|Rapid|PrePositioning)\b')
_RE_SEQ_Z = re.compile(r'\bZ\s*=\s*([-+]?[\d.]+)')
#: garde-fou: au-delà, le pliage par passe coûterait plus qu'il
#: n'apporte (profils 3D où chaque ligne a son propre Z)
_MAX_PASS_REGIONS = 2000

_GEN_HEADER = "# File generated by NeoDrive"


def _same_but_timestamp(a: str, b: str) -> bool:
    """Égalité de deux codes SimPl en ignorant la ligne d'horodatage
    de génération (1re ligne), seul élément volatile du code généré."""
    if a == b:
        return True
    if not (a.startswith(_GEN_HEADER) and b.startswith(_GEN_HEADER)):
        return False
    ia = a.find('\n')
    ib = b.find('\n')
    if ia < 0 or ib < 0:
        return False
    return a[ia:] == b[ib:]


#: le bloc NDMETA change d'un bout à l'autre au moindre réglage
_PREFIXE_META = "# NDMETA:"
#: au-delà, deux lignes différentes ne se recalent plus: autant tout refaire
_FENETRE_RECALAGE = 64


def _morceaux_changes(a: list, b: list):
    """Les morceaux qui diffèrent entre deux listes de lignes presque
    identiques: [(i0, i1, j0, j1)], a[i0:i1] devient b[j0:j1]. None si
    elles ne se recalent pas vite (ce n'est plus une retouche)."""
    morceaux = []
    i = j = 0
    na, nb = len(a), len(b)
    while i < na and j < nb:
        if a[i] == b[j]:
            i += 1
            j += 1
            continue
        recale = None
        for somme in range(1, _FENETRE_RECALAGE + 1):
            for da in range(somme + 1):
                db = somme - da
                if (i + da < na and j + db < nb and a[i + da] == b[j + db]
                        and a[i + da + 1:i + da + 3]
                        == b[j + db + 1:j + db + 3]):
                    recale = (da, db)
                    break
            if recale:
                break
        if recale is None:
            return None
        morceaux.append((i, i + recale[0], j, j + recale[1]))
        i += recale[0]
        j += recale[1]
    if i < na or j < nb:
        morceaux.append((i, na, j, nb))
    return morceaux


def _plage_meta(texte: str, lignes: list) -> tuple:
    """Les lignes [début, fin[ du bloc NDMETA (vide s'il n'y en a pas)."""
    pos = texte.find(_PREFIXE_META)
    if pos < 0:
        return len(lignes), len(lignes)
    debut = fin = texte.count("\n", 0, pos)
    while fin < len(lignes) and lignes[fin].startswith(_PREFIXE_META):
        fin += 1
    return debut, fin


def _morceaux_du_code(ta: str, la: list, tb: str, lb: list):
    """Les morceaux qui changent d'un code à l'autre: le bloc NDMETA d'un
    tenant (même s'il change de longueur), le reste ligne à ligne."""
    a0, a1 = _plage_meta(ta, la)
    b0, b1 = _plage_meta(tb, lb)
    avant = _morceaux_changes(la[:a0], lb[:b0])
    apres = _morceaux_changes(la[a1:], lb[b1:])
    if avant is None or apres is None:
        return None
    meta = [(a0, a1, b0, b1)] if la[a0:a1] != lb[b0:b1] else []
    return avant + meta + [(i0 + a1, i1 + a1, j0 + b1, j1 + b1)
                           for i0, i1, j0, j1 in apres]


def _lignes_apres(lignes: set, morceaux: list) -> set:
    """Les numéros de ligne une fois les morceaux remplacés (ceux qui sont
    dans un morceau disparaissent)."""
    resultat = set()
    for n in lignes:
        decalage = 0
        for i0, i1, j0, j1 in morceaux:
            if n >= i1:
                decalage += (j1 - j0) - (i1 - i0)
            elif n >= i0:
                break
            else:
                resultat.add(n + decalage)
                break
        else:
            resultat.add(n + decalage)
    return resultat


class SimPlSyntaxHighlighter(QSyntaxHighlighter):
    """Coloration syntaxique pour le langage SimPl.

    Sur un gros programme, Qt recolore TOUT le document a chaque
    `setPlainText`: 88 000 lignes coutaient 1,8 s a chaque frappe qui
    change le code. En mode `lazy`, seules les lignes de la fenetre
    demandee sont colorees, et l'editeur redemande la fenetre quand on
    fait defiler."""

    def __init__(self, document: QTextDocument):
        super().__init__(document)
        self._rules = []
        #: coloration limitee a une fenetre de lignes
        self._lazy = False
        self._win_first = 0
        self._win_last = -1
        #: lignes deja colorees (evite de les refaire au defilement)
        self._done: set = set()

        # Mots-clés de structure
        kw_format = QTextCharFormat()
        kw_format.setForeground(QColor("#cba6f7"))  # mauve
        kw_format.setFontWeight(QFont.Weight.Bold)
        keywords = [
            r'\bmodule\b', r'\busing\b', r'\bimport\b',
            r'\bexport\b', r'\bprogram\b', r'\bendprogram\b',
            r'\bend\b', r'\bif\b', r'\bendif\b', r'\belse\b',
            r'\breturn\b', r'\breturns\b',
        ]
        # UNE seule regex par famille (alternation) au lieu d'une par
        # mot: le surligneur passait ~65 regex sur CHAQUE ligne à
        # chaque régénération du code — de loin le poste le plus cher.
        self._rules.append(
            (self._alternation(keywords, ignorecase=True), kw_format))

        # Commandes CNC
        cmd_format = QTextCharFormat()
        cmd_format.setForeground(QColor("#89b4fa"))  # blue
        cmd_format.setFontWeight(QFont.Weight.Bold)
        # toutes les commandes du manuel SimPL (src/core/
        # simpl_commandes.py); les cycles d'usinage ont leur couleur
        from src.core.simpl_commandes import COMMANDES
        commands = [rf'\b{nom}\b' for nom, info in COMMANDES.items()
                    if info[0] != "Cycles d'usinage"]
        self._rules.append((self._alternation(commands), cmd_format))

        # Opérations d'usinage
        op_format = QTextCharFormat()
        op_format.setForeground(QColor("#a6e3a1"))  # green
        op_format.setFontWeight(QFont.Weight.Bold)
        operations = [rf'\b{nom}\b' for nom, info in COMMANDES.items()
                      if info[0] == "Cycles d'usinage"] + [
            r'\bEngrave::StandardTextEngrave\b',
            r'\bPattern::RectanglePattern\b',
            r'\bPattern::CirclePattern\b',
            r'\bPattern::CircularPattern\b',
        ]
        self._rules.append((self._alternation(operations), op_format))

        # Paramètres (mot=valeur)
        param_format = QTextCharFormat()
        param_format.setForeground(QColor("#f9e2af"))  # yellow
        self._rules.append((
            re.compile(
                r'\b(widthX|widthY|depth|infeedZ|strokeRapidZ|strokeCuttingZ|'
                r'finishingZ|finishingXY|percentageStepover|cornerRadius|'
                r'diameter|extensionX|extensionY|extensionDiameter|'
                r'diagonalInfeed|infeedFinishingZ|angle|text|charWidth|'
                r'charHeight|textWidth|rotation|slant|threadName|'
                r'finishing|approach|plunge|ramp|roughing|'
                r'xCount|yCount|deltaX|deltaY|callProgram|'
                r'name|type|newRpm|skipRestoring|allowedDeviation|'
                r'message|caption)\b'),
            param_format
        ))

        # Valeurs On/Off et options
        val_format = QTextCharFormat()
        val_format.setForeground(QColor("#fab387"))  # peach
        values = [
            r'\bOn\b', r'\bOff\b', r'\btrue\b', r'\bfalse\b',
            r'\bMetric\b', r'\bInside\b', r'\bOutside\b', r'\bOver\b',
            r'\bBothWays\b', r'\bCenter\b',
            r'\bRightHandThread\b', r'\bLeftHandThread\b',
            r'\bConventionalMilling\b', r'\bClimbMilling\b',
            r'\bAlcohol\b', r'\bSpray\b', r'\bFlood\b',
            r'\bYes\b', r'\bNo\b',
            r'\bDialogResult\.Yes\b', r'\bDialogResult\.No\b',
        ]
        self._rules.append((self._alternation(values), val_format))

        # Nombres
        num_format = QTextCharFormat()
        num_format.setForeground(QColor("#94e2d5"))  # teal
        self._rules.append((
            re.compile(r'\b[+-]?\d+\.?\d*\b'), num_format))

        # Chaînes
        str_format = QTextCharFormat()
        str_format.setForeground(QColor("#a6e3a1"))  # green
        self._rules.append((re.compile(r'"[^"]*"'), str_format))

        # Annotations @...@
        annot_format = QTextCharFormat()
        annot_format.setForeground(QColor("#6c7086"))  # overlay0
        annot_format.setFontItalic(True)
        self._rules.append((re.compile(r'@[^@]*@'), annot_format))

        # Commentaires #
        comment_format = QTextCharFormat()
        comment_format.setForeground(QColor("#585b70"))  # surface2
        comment_format.setFontItalic(True)
        self._rules.append((re.compile(r'#.*$'), comment_format))
        self._comment_format = comment_format

    @staticmethod
    def _alternation(patterns: list, ignorecase: bool = False):
        """Fusionne des motifs `\\bmot\\b` en UNE regex d'alternance.
        Les alternatives sont triées du plus long au plus court pour
        que `DrillMilling` l'emporte sur `Drill` (le moteur re prend
        la première alternative qui matche, pas la plus longue)."""
        words = []
        for p in patterns:
            core = p
            if core.startswith(r'\b'):
                core = core[2:]
            if core.endswith(r'\b'):
                core = core[:-2]
            words.append(core)
        words.sort(key=len, reverse=True)
        joined = r'\b(?:' + '|'.join(words) + r')\b'
        flags = re.IGNORECASE if ignorecase else 0
        return re.compile(joined, flags)

    def set_lazy(self, enabled: bool):
        """Active la coloration a la demande et oublie ce qui est fait."""
        self._lazy = bool(enabled)
        self._win_first, self._win_last = 0, -1
        self._done.clear()

    def highlight_window(self, first: int, last: int):
        """Colore les lignes [first, last] pas encore traitees."""
        if not self._lazy:
            return
        doc = self.document()
        if doc is None:
            return
        first = max(0, first)
        last = min(last, doc.blockCount() - 1)
        manquantes = [n for n in range(first, last + 1)
                      if n not in self._done]
        if not manquantes:
            return
        self._win_first, self._win_last = first, last
        block = doc.findBlockByNumber(manquantes[0])
        precedent = manquantes[0]
        for num in manquantes:
            while block.isValid() and precedent < num:
                block = block.next()
                precedent += 1
            if not block.isValid():
                break
            self.rehighlightBlock(block)

    def highlightBlock(self, text: str):
        if not text:
            return
        if self._lazy:
            num = self.currentBlock().blockNumber()
            if not (self._win_first <= num <= self._win_last):
                return          # hors de la fenetre: rien a peindre
            self._done.add(num)
        # Ligne entièrement en commentaire (Tool List, NDMETA, repères
        # de section...): un seul setFormat au lieu des 9 regex — ces
        # lignes représentent une grosse part du code généré.
        stripped = text.lstrip()
        if stripped.startswith('#'):
            self.setFormat(0, len(text), self._comment_format)
            return
        for pattern, fmt in self._rules:
            for match in pattern.finditer(text):
                self.setFormat(match.start(), match.end() - match.start(),
                               fmt)


